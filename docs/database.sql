CREATE DATABASE IF NOT EXISTS erp_little_horizons CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE erp_little_horizons;

SET FOREIGN_KEY_CHECKS = 0;
DROP TABLE IF EXISTS prestamos_profesor, prestamos_estudiante, recursos, facturas, pagos,
  valores_personalizados, conceptos_pago, participaciones_evento, eventos, inscripciones_club,
  clubes, asistencias, registros_academicos, inscripciones_materia, asignaciones_profesor,
  materias, profesores, estudiantes, acudientes;
SET FOREIGN_KEY_CHECKS = 1;

-- ============================ SECTION 1: DDL ============================
CREATE TABLE acudientes (
  id_acudiente INT AUTO_INCREMENT PRIMARY KEY,
  nombre_completo VARCHAR(120) NOT NULL,
  documento_identidad VARCHAR(20) NOT NULL UNIQUE,
  telefono VARCHAR(20) NOT NULL,
  correo VARCHAR(100),
  direccion VARCHAR(150) NOT NULL
) ENGINE=InnoDB;

CREATE TABLE estudiantes (
  id_estudiante INT AUTO_INCREMENT PRIMARY KEY,
  nombre_completo VARCHAR(120) NOT NULL,
  documento_identidad VARCHAR(20) NOT NULL UNIQUE,
  fecha_nacimiento DATE NOT NULL,
  direccion VARCHAR(150) NOT NULL,
  contacto_emergencia VARCHAR(100) NOT NULL,
  id_acudiente INT NOT NULL,
  grado TINYINT NOT NULL,
  anio_matricula SMALLINT NOT NULL,
  estado ENUM('Activo','Graduado','Retirado') NOT NULL DEFAULT 'Activo',
  CONSTRAINT ck_estudiantes_grado CHECK (grado BETWEEN 0 AND 11),
  CONSTRAINT fk_estudiantes_acudiente FOREIGN KEY (id_acudiente) REFERENCES acudientes(id_acudiente),
  INDEX idx_estudiantes_grado (grado),
  INDEX idx_estudiantes_acudiente (id_acudiente)
) ENGINE=InnoDB;

CREATE TABLE profesores (
  id_profesor INT AUTO_INCREMENT PRIMARY KEY,
  nombre_completo VARCHAR(120) NOT NULL,
  documento_identidad VARCHAR(20) NOT NULL UNIQUE,
  especializacion VARCHAR(100) NOT NULL,
  telefono VARCHAR(20) NOT NULL,
  correo VARCHAR(100)
) ENGINE=InnoDB;

CREATE TABLE materias (
  id_materia INT AUTO_INCREMENT PRIMARY KEY,
  nombre VARCHAR(80) NOT NULL,
  grado TINYINT NOT NULL,
  CONSTRAINT ck_materias_grado CHECK (grado BETWEEN 0 AND 11),
  CONSTRAINT uq_materias UNIQUE (nombre, grado)
) ENGINE=InnoDB;

CREATE TABLE asignaciones_profesor (
  id_asignacion INT AUTO_INCREMENT PRIMARY KEY,
  id_profesor INT NOT NULL,
  id_materia INT NOT NULL,
  dia_semana ENUM('Lunes','Martes','Miercoles','Jueves','Viernes') NOT NULL,
  hora_inicio TIME NOT NULL,
  hora_fin TIME NOT NULL,
  CONSTRAINT ck_asignaciones_horas CHECK (hora_fin > hora_inicio),
  CONSTRAINT fk_asig_profesor FOREIGN KEY (id_profesor) REFERENCES profesores(id_profesor),
  CONSTRAINT fk_asig_materia FOREIGN KEY (id_materia) REFERENCES materias(id_materia),
  CONSTRAINT uq_asig_profesor_horario UNIQUE (id_profesor, dia_semana, hora_inicio)
) ENGINE=InnoDB;

CREATE TABLE inscripciones_materia (
  id_inscripcion INT AUTO_INCREMENT PRIMARY KEY,
  id_estudiante INT NOT NULL,
  id_materia INT NOT NULL,
  anio_academico SMALLINT NOT NULL,
  CONSTRAINT fk_insc_estudiante FOREIGN KEY (id_estudiante) REFERENCES estudiantes(id_estudiante),
  CONSTRAINT fk_insc_materia FOREIGN KEY (id_materia) REFERENCES materias(id_materia),
  CONSTRAINT uq_insc_materia UNIQUE (id_estudiante, id_materia, anio_academico)
) ENGINE=InnoDB;

CREATE TABLE registros_academicos (
  id_registro INT AUTO_INCREMENT PRIMARY KEY,
  id_estudiante INT NOT NULL,
  id_materia INT NOT NULL,
  periodo ENUM('I','II','III','IV','Final') NOT NULL,
  anio_academico SMALLINT NOT NULL,
  nota DECIMAL(2,1) NOT NULL,
  CONSTRAINT ck_registros_nota CHECK (nota BETWEEN 0.0 AND 5.0),
  CONSTRAINT fk_reg_estudiante FOREIGN KEY (id_estudiante) REFERENCES estudiantes(id_estudiante),
  CONSTRAINT fk_reg_materia FOREIGN KEY (id_materia) REFERENCES materias(id_materia),
  CONSTRAINT uq_registro UNIQUE (id_estudiante, id_materia, periodo, anio_academico)
) ENGINE=InnoDB;

CREATE TABLE asistencias (
  id_asistencia INT AUTO_INCREMENT PRIMARY KEY,
  id_estudiante INT NOT NULL,
  id_materia INT NOT NULL,
  fecha DATE NOT NULL,
  estado ENUM('Presente','Ausente','Tardanza','Excusa Medica') NOT NULL,
  CONSTRAINT fk_asist_estudiante FOREIGN KEY (id_estudiante) REFERENCES estudiantes(id_estudiante),
  CONSTRAINT fk_asist_materia FOREIGN KEY (id_materia) REFERENCES materias(id_materia),
  CONSTRAINT uq_asistencia UNIQUE (id_estudiante, id_materia, fecha),
  INDEX idx_asistencias_fecha (fecha)
) ENGINE=InnoDB;

CREATE TABLE clubes (
  id_club INT AUTO_INCREMENT PRIMARY KEY,
  nombre VARCHAR(80) NOT NULL UNIQUE,
  descripcion VARCHAR(255) NOT NULL,
  cupo_maximo INT NOT NULL,
  id_profesor INT NOT NULL,
  activo BOOLEAN NOT NULL DEFAULT TRUE,
  CONSTRAINT ck_clubes_cupo CHECK (cupo_maximo > 0),
  CONSTRAINT fk_clubes_profesor FOREIGN KEY (id_profesor) REFERENCES profesores(id_profesor)
) ENGINE=InnoDB;

CREATE TABLE inscripciones_club (
  id_inscripcion_club INT AUTO_INCREMENT PRIMARY KEY,
  id_club INT NOT NULL,
  id_estudiante INT NOT NULL,
  fecha_ingreso DATE NOT NULL,
  estado ENUM('Activo','Retirado') NOT NULL DEFAULT 'Activo',
  CONSTRAINT fk_ic_club FOREIGN KEY (id_club) REFERENCES clubes(id_club),
  CONSTRAINT fk_ic_estudiante FOREIGN KEY (id_estudiante) REFERENCES estudiantes(id_estudiante),
  CONSTRAINT uq_inscripcion_club UNIQUE (id_club, id_estudiante)
) ENGINE=InnoDB;

CREATE TABLE eventos (
  id_evento INT AUTO_INCREMENT PRIMARY KEY,
  nombre VARCHAR(100) NOT NULL,
  fecha DATE NOT NULL,
  descripcion VARCHAR(255),
  tipo ENUM('Academico','Cultural','Deportivo','Social') NOT NULL,
  tiene_competencia BOOLEAN NOT NULL DEFAULT FALSE
) ENGINE=InnoDB;

CREATE TABLE participaciones_evento (
  id_participacion INT AUTO_INCREMENT PRIMARY KEY,
  id_evento INT NOT NULL,
  id_estudiante INT NOT NULL,
  posicion ENUM('1er lugar','2do lugar','3er lugar','Participante') NOT NULL DEFAULT 'Participante',
  CONSTRAINT fk_pe_evento FOREIGN KEY (id_evento) REFERENCES eventos(id_evento),
  CONSTRAINT fk_pe_estudiante FOREIGN KEY (id_estudiante) REFERENCES estudiantes(id_estudiante),
  CONSTRAINT uq_participacion UNIQUE (id_evento, id_estudiante)
) ENGINE=InnoDB;

CREATE TABLE conceptos_pago (
  id_concepto INT AUTO_INCREMENT PRIMARY KEY,
  nombre VARCHAR(80) NOT NULL UNIQUE,
  valor_base DECIMAL(12,2) NOT NULL,
  aplica_iva BOOLEAN NOT NULL DEFAULT FALSE,
  CONSTRAINT ck_conceptos_valor CHECK (valor_base >= 0)
) ENGINE=InnoDB;

CREATE TABLE valores_personalizados (
  id_valor INT AUTO_INCREMENT PRIMARY KEY,
  id_estudiante INT NOT NULL,
  id_concepto INT NOT NULL,
  valor DECIMAL(12,2) NOT NULL,
  motivo VARCHAR(100),
  CONSTRAINT fk_vp_estudiante FOREIGN KEY (id_estudiante) REFERENCES estudiantes(id_estudiante),
  CONSTRAINT fk_vp_concepto FOREIGN KEY (id_concepto) REFERENCES conceptos_pago(id_concepto),
  CONSTRAINT uq_valor_personalizado UNIQUE (id_estudiante, id_concepto)
) ENGINE=InnoDB;

CREATE TABLE pagos (
  id_pago INT AUTO_INCREMENT PRIMARY KEY,
  id_estudiante INT NOT NULL,
  id_concepto INT NOT NULL,
  valor DECIMAL(12,2) NOT NULL,
  fecha_vencimiento DATE NOT NULL,
  fecha_pago DATE NULL,
  metodo_pago ENUM('Efectivo','Transferencia','Tarjeta') NULL,
  numero_recibo VARCHAR(20) NULL UNIQUE,
  estado ENUM('Pendiente','Pagado') NOT NULL DEFAULT 'Pendiente',
  CONSTRAINT ck_pagos_valor CHECK (valor > 0),
  CONSTRAINT fk_pagos_estudiante FOREIGN KEY (id_estudiante) REFERENCES estudiantes(id_estudiante),
  CONSTRAINT fk_pagos_concepto FOREIGN KEY (id_concepto) REFERENCES conceptos_pago(id_concepto),
  INDEX idx_pagos_estado (estado, fecha_vencimiento)
) ENGINE=InnoDB;

CREATE TABLE facturas (
  id_factura INT AUTO_INCREMENT PRIMARY KEY,
  id_pago INT NOT NULL UNIQUE,
  fecha_emision DATETIME NOT NULL,
  subtotal DECIMAL(12,2) NOT NULL,
  iva DECIMAL(12,2) NOT NULL,
  total DECIMAL(12,2) NOT NULL,
  cufe CHAR(96) NOT NULL,
  ruta_archivo VARCHAR(255) NOT NULL,
  CONSTRAINT fk_facturas_pago FOREIGN KEY (id_pago) REFERENCES pagos(id_pago)
) ENGINE=InnoDB;

CREATE TABLE recursos (
  id_recurso INT AUTO_INCREMENT PRIMARY KEY,
  codigo VARCHAR(20) NOT NULL UNIQUE,
  nombre VARCHAR(100) NOT NULL,
  categoria ENUM('Libro','Equipo de Laboratorio','Equipo Deportivo','Dispositivo Tecnologico') NOT NULL,
  estado ENUM('Disponible','Prestado','En Mantenimiento','Dado de Baja') NOT NULL DEFAULT 'Disponible',
  ubicacion VARCHAR(80) NOT NULL
) ENGINE=InnoDB;

CREATE TABLE prestamos_estudiante (
  id_prestamo INT AUTO_INCREMENT PRIMARY KEY,
  id_recurso INT NOT NULL,
  id_estudiante INT NOT NULL,
  fecha_prestamo DATE NOT NULL,
  fecha_devolucion_programada DATE NOT NULL,
  fecha_devolucion_real DATE NULL,
  estado ENUM('Activo','Devuelto','Vencido') NOT NULL DEFAULT 'Activo',
  CONSTRAINT ck_pe_fechas CHECK (fecha_devolucion_programada >= fecha_prestamo),
  CONSTRAINT fk_pres_est_recurso FOREIGN KEY (id_recurso) REFERENCES recursos(id_recurso),
  CONSTRAINT fk_pres_est_estudiante FOREIGN KEY (id_estudiante) REFERENCES estudiantes(id_estudiante)
) ENGINE=InnoDB;

CREATE TABLE prestamos_profesor (
  id_prestamo INT AUTO_INCREMENT PRIMARY KEY,
  id_recurso INT NOT NULL,
  id_profesor INT NOT NULL,
  fecha_prestamo DATE NOT NULL,
  fecha_devolucion_programada DATE NOT NULL,
  fecha_devolucion_real DATE NULL,
  estado ENUM('Activo','Devuelto','Vencido') NOT NULL DEFAULT 'Activo',
  CONSTRAINT ck_pp_fechas CHECK (fecha_devolucion_programada >= fecha_prestamo),
  CONSTRAINT fk_pres_prof_recurso FOREIGN KEY (id_recurso) REFERENCES recursos(id_recurso),
  CONSTRAINT fk_pres_prof_profesor FOREIGN KEY (id_profesor) REFERENCES profesores(id_profesor)
) ENGINE=InnoDB;

